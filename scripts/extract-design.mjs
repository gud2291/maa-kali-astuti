/* Design extraction pipeline (F2).
   Evaluates design/mka-core.js → mka-astro.js → mka-home.js in jsdom and writes:
     • DATA members          → src/lib/data/*.json
     • static ART (no text,   → public/svg/<group>/<name>.svg   (rendered with <img>)
       no data-amb)
     • inline ART (animated,  → src/lib/art/*.ts                (string constants, inlined by
       or has <text>)                                            signature components)
   Why <text> forces inline: an SVG loaded through <img> cannot use the page's web fonts,
   so Fraunces / Manrope / Tiro text would fall back to system fonts.

   Instance ids: builders take a `u` suffix for their <defs> ids. When `u` only feeds ids,
   the string is emitted with the token `__U__` and the component swaps in its own suffix
   (see src/lib/art/uid.ts). When `u` also seeds randomness, the design's call-site `u`
   is kept verbatim so the output matches the prototype.

   Run: node scripts/extract-design.mjs   (dev-time generator; re-run after design changes) */
import { mkdirSync, writeFileSync, rmSync, existsSync } from "node:fs";
import path from "node:path";
import { loadDesign, ROOT } from "./lib-design-env.mjs";

const { M, A, H, dom } = await loadDesign();

const DATA_DIR = path.join(ROOT, "src/lib/data");
const ART_DIR = path.join(ROOT, "src/lib/art");
const SVG_DIR = path.join(ROOT, "public/svg");
const report = { data: [], svg: [], art: [], warn: [] };

/* ---------------- helpers ---------------- */
const plain = (v) => JSON.parse(JSON.stringify(v, (k, x) => (typeof x === "function" ? undefined : x)));
const writeJson = (name, value) => {
  mkdirSync(DATA_DIR, { recursive: true });
  writeFileSync(path.join(DATA_DIR, name + ".json"), JSON.stringify(plain(value), null, 2) + "\n");
  report.data.push(name + ".json");
};
const XMLNS = 'xmlns="http://www.w3.org/2000/svg"';
const standalone = (svg) => {
  let s = String(svg).trim();
  if (!s.startsWith("<svg")) throw new Error("not an <svg>: " + s.slice(0, 60));
  if (!/\sxmlns=/.test(s.slice(0, s.indexOf(">")))) s = s.replace(/^<svg/, "<svg " + XMLNS);
  if (/\shref="/.test(s) && !/xmlns:xlink/.test(s)) s = s.replace(/^<svg/, '<svg xmlns:xlink="http://www.w3.org/1999/xlink"');
  return s;
};
const hasText = (s) => /<text[\s>]/.test(s);
const hasAmb = (s) => /\sdata-amb=/.test(s);
const writeSvg = (rel, svg) => {
  const s = standalone(svg);
  if (hasText(s)) report.warn.push(`public/svg/${rel} contains <text> (fonts fall back inside <img>)`);
  if (hasAmb(s)) report.warn.push(`public/svg/${rel} contains data-amb (will not animate inside <img>)`);
  const file = path.join(SVG_DIR, rel);
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, s + "\n");
  report.svg.push(rel);
};
/* Build with two different tokens: if `u` only feeds ids, return the tokenized string. */
const U = "__U__";
const tokenized = (build) => {
  const a = String(build(U)), b = String(build("__V__"));
  return a.split(U).join("__V__") === b ? a : null;
};
const lit = (s) => JSON.stringify(String(s));
const artModule = (name, doc, entries) => {
  mkdirSync(ART_DIR, { recursive: true });
  let out = `/* GENERATED by scripts/extract-design.mjs — do not edit by hand.\n   ${doc}\n   Trusted, build-generated SVG markup: the only content allowed in dangerouslySetInnerHTML. */\n\n`;
  for (const [k, v] of entries) out += (v.doc ? `/** ${v.doc} */\n` : "") + `export const ${k} = ${v.code};\n\n`;
  writeFileSync(path.join(ART_DIR, name + ".ts"), out.trimEnd() + "\n");
  report.art.push(name + ".ts");
};
const str = (s, doc) => ({ code: lit(s), doc });
const rec = (o, doc, type = "Record<string, string>") => ({
  code: `{\n${Object.entries(o).map(([k, v]) => `  ${/^[a-z_$][\w$]*$/i.test(k) ? k : lit(k)}: ${typeof v === "string" ? lit(v) : JSON.stringify(v)},`).join("\n")}\n} as const satisfies ${type}`,
  doc,
});
/* strict tokenized build or fail loudly, so a design change can't silently break ids */
const tok = (label, build) => {
  const t = tokenized(build);
  if (t == null) throw new Error(label + ": `u` seeds randomness — emit per call-site instead");
  return t;
};
/* u seeds randomness: build with the design's canonical call-site u (so the art matches that page),
   then swap that literal for the token so each instance still gets unique ids. */
const seeded = (label, build, u) => {
  const t = tokenized(build);
  if (t != null) return t;
  const out = String(build(u)).split(u).join(U);
  if (!/ id="/.test(out) || out.includes(U)) return out;
  throw new Error(label + ': canonical u not found in ids');
};
const kebab = (s) => String(s).toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

/* ---------------- clean previous output ---------------- */
for (const d of [SVG_DIR]) if (existsSync(d)) rmSync(d, { recursive: true, force: true });

